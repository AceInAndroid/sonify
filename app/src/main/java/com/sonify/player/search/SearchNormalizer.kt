    /** 保持 1:1 字符位置不变的归一化（全角→半角、小写、繁→简） */
    fun normalize1To1(input: String): String {
        if (input.isEmpty()) return ""
        val sb = StringBuilder(input.length)
        for (ch in input) {
            val half = when (ch.code) {
                0x3000 -> ' '
                in 0xFF01..0xFF5E -> (ch.code - 0xFEE0).toChar()
                else -> ch
            }
            val lower = half.lowercaseChar()
            sb.append(TRAD_TO_SIMP[lower] ?: lower)
        }
        return sb.toString()
    }

    /** 将搜索词拆分为归一化后的非空多词 token */
    fun tokenize(query: String): List<String> =
        normalize1To1(query)
            .trim()
            .split(Regex("\\s+"))
            .filter { it.isNotEmpty() }

    /**
     * 在原展示文本中定位命中 token 的字符区间 [start, endExclusive)，
     * 即使输入简体「周杰伦」而展示繁体「周杰倫」，也能准确标亮原字。
     */
    fun findHighlightRanges(displayText: String, normalizedTokens: List<String>): List<IntRange> {
        if (displayText.isEmpty() || normalizedTokens.isEmpty()) return emptyList()
        val norm = normalize1To1(displayText)
        val raw = mutableListOf<IntRange>()
        for (tok in normalizedTokens) {
            var from = 0
            while (from < norm.length) {
                val idx = norm.indexOf(tok, from)
                if (idx < 0) break
                raw += idx until (idx + tok.length)
                from = idx + tok.length
            }
        }
        if (raw.isEmpty()) return emptyList()
        raw.sortBy { it.first }
        val merged = mutableListOf<IntRange>()
        for (r in raw) {
            val last = merged.lastOrNull()
            if (last != null && r.first <= last.last + 1) {
                merged[merged.lastIndex] = last.first..maxOf(last.last, r.last)
            } else {
                merged += r
            }
        }
        return merged
    }
